#!/usr/bin/env node
/**
 * Import the designer's single-file prototype into the site.
 *
 *   node scripts/import-prototype.mjs "<path to peptides-costa-rica-site.html>"
 *
 * The prototype ships its whole stylesheet and its brand images inline. This
 * writes:
 *
 *   app/site.css      the prototype's CSS, every rule scoped under `.pcr-site`
 *   public/site/*     the brand images (logo, review badges, press logos)
 *
 * Scoping is what lets the new design live beside the pages that still use the
 * cloned WordPress styles in globals.css: neither stylesheet can reach the
 * other's markup. Re-run it whenever the designer sends a new version of the
 * file, rather than hand-editing app/site.css.
 *
 * Product photos are not imported. The prototype's later revisions read them
 * from the catalog's own `product-pics` storage, which is what the product rows'
 * `image_url` already points at.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCOPE = '.pcr-site';

/** The images the chrome uses, in the order they first appear in the file. */
const BRAND_IMAGES = [
  'logo',
  'google',
  'trustpilot',
  'facebook',
  'press-tico-times',
  'press-costa-rica-news',
  'press-la-nacion',
];

function scopeSelector(selector) {
  const s = selector.trim();
  if (s === ':root' || s === 'body') return SCOPE;
  if (s.startsWith('body::')) return SCOPE + s.slice(4);
  // `html.sxlock` and `body.noscroll` are toggled on the document by the
  // search and cart; they stay global so the page behind can be locked.
  if (/^(html|body)([.:[]|$)/.test(s)) return s;
  return `${SCOPE} ${s}`;
}

function scopeCss(css) {
  const root = postcss.parse(css);
  root.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.map(scopeSelector);
  });
  return root.toString();
}

function main() {
  const src = process.argv[2];
  if (!src) {
    console.error('usage: node scripts/import-prototype.mjs <prototype.html>');
    process.exit(1);
  }
  const html = fs.readFileSync(src, 'utf8');

  const styles = [...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]);
  if (!styles.length) throw new Error('no <style> blocks found');
  const css = [
    '/* Generated by scripts/import-prototype.mjs from the designer\'s prototype. Do not edit by hand. */',
    scopeCss(styles.join('\n')),
  ].join('\n');
  fs.writeFileSync(path.join(ROOT, 'app', 'site.css'), `${css}\n`);

  // Brand images: the first distinct inline images outside the product map.
  const markup = html.slice(0, html.indexOf('<script>var IMG='));
  const seen = [];
  for (const m of markup.matchAll(/data:image\/webp;base64,([A-Za-z0-9+/=]+)/g)) {
    if (!seen.includes(m[1])) seen.push(m[1]);
    if (seen.length === BRAND_IMAGES.length) break;
  }
  const outDir = path.join(ROOT, 'public', 'site');
  fs.mkdirSync(outDir, { recursive: true });
  seen.forEach((b64, i) => {
    fs.writeFileSync(path.join(outDir, `${BRAND_IMAGES[i]}.webp`), Buffer.from(b64, 'base64'));
  });

  console.log(`app/site.css: ${css.length} chars from ${styles.length} style blocks`);
  console.log(`public/site: ${seen.length} images`);
}

main();
