/**
 * Mirror the ElementsKit icon font, and only the glyphs this site uses.
 *
 * WHY THIS EXISTS
 *
 * The site draws icons two ways. Font Awesome is inlined by WordPress as an
 * `<svg>`, so the harvest captures it whole and it needs nothing at runtime.
 * ElementsKit is a WEBFONT: the markup is `<i class="icon icon-savings">` and
 * the glyph comes from `elementskit.woff` via a `content: "\e979"` rule. Keep
 * the class without the font and every one of those icons renders as an empty
 * box — which is why they were left out of the clone entirely at first.
 *
 * The plugin's own stylesheet is 83KB and declares roughly 2,000 glyphs. This
 * site uses a few dozen, so shipping all of it would be most of a stylesheet
 * for nothing. This reads the classes the harvest actually recorded and emits
 * rules for those alone.
 *
 * Re-runnable: rewrites both outputs from scratch each time. Run it after any
 * harvest that could introduce a new icon.
 *
 * Usage: node scripts/mirror-icon-font.mjs
 */

import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PAGES = resolve(ROOT, 'data/pages');
const ORIGIN = 'https://peptidescostarica.net';
const PLUGIN = '/wp-content/plugins/elementskit-lite/modules/elementskit-icon-pack/assets';

const CSS_URL = `${ORIGIN}${PLUGIN}/css/ekiticons.css`;
const FONT_URL = `${ORIGIN}${PLUGIN}/fonts/elementskit.woff`;
const FONT_OUT = resolve(ROOT, `public${PLUGIN}/fonts/elementskit.woff`);
const CSS_OUT = resolve(ROOT, 'app/ekiticons.css');

/** Every `icon-*` class the harvest recorded, across all page groups. */
async function usedClasses() {
  const used = new Set();
  const walk = (section) => {
    const c = section.content ?? {};
    if (c.iconClass) for (const cls of c.iconClass.split(/\s+/)) used.add(cls);
    (c.children ?? []).forEach(walk);
  };

  for (const file of await readdir(PAGES)) {
    if (!file.endsWith('.json')) continue;
    const data = JSON.parse(await readFile(resolve(PAGES, file), 'utf8'));
    for (const page of data.pages ?? []) (page.sections ?? []).forEach(walk);
  }
  return used;
}

const get = async (url, as = 'text') => {
  const res = await fetch(url, {
    headers: { 'user-agent': 'peptidescostarica-rebuild-harvest' },
    signal: AbortSignal.timeout(60000),
  });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return as === 'text' ? res.text() : Buffer.from(await res.arrayBuffer());
};

const used = await usedClasses();
if (!used.size) {
  console.log('mirror-icon-font: no webfont icons in the harvest — nothing to do');
  process.exit(0);
}

const css = await get(CSS_URL);

// The @font-face, repointed at the mirrored file. The plugin writes a relative
// `../fonts/…` path, which only resolves from the plugin's own CSS directory.
const face = `@font-face {
  font-family: elementskit;
  src: url('${PLUGIN}/fonts/elementskit.woff') format('woff');
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}`;

const rules = [];
const missing = [];
for (const cls of [...used].sort()) {
  if (cls === 'icon') continue; // the base class, not a glyph
  const escaped = cls.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = new RegExp(`\\.${escaped}::before[^{]*\\{content:"([^"]+)"\\}`).exec(css);
  if (!match) {
    missing.push(cls);
    continue;
  }
  rules.push(`.${cls}::before { content: "${match[1]}"; }`);
}

const out = `/*
 * ElementsKit icon glyphs — GENERATED by scripts/mirror-icon-font.mjs.
 * Do not edit: re-run that script instead. It emits rules only for the glyphs
 * the harvested content actually references, out of the ~2,000 the plugin
 * ships, and mirrors the font file alongside them.
 */

${face}

[class^='icon-'],
[class*=' icon-'] {
  font-family: elementskit !important;
  font-style: normal;
  font-weight: 400;
  font-variant: normal;
  line-height: 1;
  text-transform: none;
  speak: none;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${rules.join('\n')}
`;

await mkdir(dirname(FONT_OUT), { recursive: true });
await writeFile(FONT_OUT, await get(FONT_URL, 'buffer'));
await writeFile(CSS_OUT, out, 'utf8');

console.log(`mirror-icon-font: ${rules.length} glyph(s) → app/ekiticons.css`);
console.log(`  font → public${PLUGIN}/fonts/elementskit.woff`);
if (missing.length) {
  console.log(`  ${missing.length} class(es) had no glyph rule in the plugin CSS:`);
  for (const m of missing) console.log(`    ${m}`);
}
