import Link from 'next/link';
import ProductList from '@/components/product-list';
import { featuredImage } from '@/lib/featured-image';
import { t } from '@/lib/i18n';
import { imageSource, SIZES } from '@/lib/images';
import { localePath } from '@/lib/routes';
import { dedupeProducts } from '@/lib/dedupe-products';
import { posts } from '@/content/pages/posts';
import { products } from '@/content/pages/products';
import guideData from '@/data/pages/guide.json';
import mixingGuideData from '@/data/pages/mixingGuide.json';
import coreData from '@/data/pages/core.json';
import legalData from '@/data/pages/legal.json';
import categoryData from '@/data/pages/category.json';
import landerData from '@/data/pages/productLander.json';
import wooCategoryData from '@/data/pages/wooCategory.json';
import cityData from '@/data/pages/city.json';

/**
 * An index of pages, resolved from the site's own harvested data.
 *
 * The section stores only a SOURCE name, never a copy of the list. Publishing a
 * guide or product and re-running its harvest updates every index that lists
 * it, with no page edit — which is the whole reason /blog/, /peptide-guides/
 * and /shop/ could not be harvested as static content.
 *
 * An unknown source renders nothing rather than crashing, matching how the rest
 * of the vocabulary behaves.
 *
 * TWO LAYOUTS. `layout: 'cards'` is the content archive the live site shows at
 * /shop/, /blog/ and /peptide-guides/ — a picture and a heading per entry.
 * Without it the section stays the compact link list that /html-sitemap/ wants,
 * where several hundred routes have to stay scannable and a thumbnail per row
 * would be actively unhelpful.
 */
const SOURCES = {
  blogPost: () => posts,
  guide: () => guideData.pages,
  specificationSheet: () =>
    guideData.pages.filter((page) => page.en.startsWith('/peptide-specification-sheets/')),
  mixingGuide: () => mixingGuideData.pages,
  wooProduct: () => products,
  // The remaining groups, for /html-sitemap/. That page is generated by a
  // WordPress plugin, so the REST API stores no content for it at all and the
  // harvest could only ever produce a blank page. We already hold the complete
  // route inventory, so the index is built from our own data instead.
  core: () => coreData.pages,
  legal: () => legalData.pages,
  category: () => categoryData.pages,
  productLander: () => landerData.pages,
  wooCategory: () => wooCategoryData.pages,
  city: () => cityData.pages,
};

/** The link text for an entry: its own page title, in the requested language. */
function titleFor(page, lang) {
  const fromHead = t(page.head ?? {}, 'title', lang);
  if (fromHead) {
    // Page titles carry the site suffix; the list wants just the article name.
    return fromHead.split('|')[0].split('–')[0].trim() || fromHead;
  }
  return page.store?.name ?? page.slug;
}

export default function LinkList({ content, lang }) {
  const sourceEntries = SOURCES[content.source]?.() ?? [];
  const entries = content.source === 'wooProduct' ? dedupeProducts(sourceEntries) : sourceEntries;
  if (!entries.length) return null;

  // The product archives already have a card — the one the category pages use.
  // Rendering a second, near-identical one here is how the two drift apart.
  if (content.layout === 'cards' && content.source === 'wooProduct') {
    return <ProductList products={entries} lang={lang} />;
  }

  const items = entries
    .map((page) => ({ page, title: titleFor(page, lang) }))
    .sort((a, b) => a.title.localeCompare(b.title));

  // /html-sitemap/ is a route inventory, not a magazine: it lists several
  // hundred pages and wants to stay scannable, so it keeps the compact list.
  if (content.layout !== 'cards') {
    return (
      <ul className="mt-8 grid gap-4 sm:grid-cols-2">
        {items.map(({ page, title }) => (
          <li key={page.en}>
            <Link
              className="group flex h-full flex-col rounded-2xl border border-slate-200/80 bg-white p-4 shadow-[0_8px_24px_rgba(9,39,113,0.06)] transition duration-200 hover:-translate-y-1 hover:border-primary/20 hover:shadow-[0_16px_34px_rgba(9,39,113,0.12)]"
              href={localePath(page.en, lang)}
            >
              <span className="text-sm font-bold text-primary">{title}</span>
              {t(page.head ?? {}, 'description', lang) && (
                <span className="mt-1 line-clamp-2 text-xs leading-relaxed text-text-muted">
                  {t(page.head, 'description', lang)}
                </span>
              )}
            </Link>
          </li>
        ))}
      </ul>
    );
  }

  return (
    <ul className="mt-8 grid gap-5 sm:grid-cols-2 lg:grid-cols-3">
      {items.map(({ page, title }) => {
        // Resolved so an unservable image is skipped, not rendered broken.
        const image = imageSource(featuredImage(page));
        const description = t(page.head ?? {}, 'description', lang);
        return (
          <li key={page.en}>
            <Link
              className="group flex h-full flex-col rounded-2xl border border-slate-200/80 bg-white p-4 shadow-[0_8px_24px_rgba(9,39,113,0.06)] transition duration-200 hover:-translate-y-1 hover:border-primary/20 hover:shadow-[0_16px_34px_rgba(9,39,113,0.12)]"
              href={localePath(page.en, lang)}
            >
              {image.src && (
                // eslint-disable-next-line @next/next/no-img-element -- harvested
                <img
                  alt={title}
                  className="mb-4 aspect-[4/3] w-full rounded-xl bg-slate-100 object-cover"
                  loading="lazy"
                  sizes={SIZES.productCard}
                  {...image}
                />
              )}
              <h2 className="text-base font-bold leading-6 text-primary transition group-hover:text-accent">{title}</h2>
              {description && (
                <span className="mt-1 line-clamp-3 text-xs leading-relaxed text-text-muted">
                  {description}
                </span>
              )}
            </Link>
          </li>
        );
      })}
    </ul>
  );
}
