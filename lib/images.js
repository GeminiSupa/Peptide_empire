/**
 * Content images are stored in content/ as PATHS ONLY
 * (e.g. `/wp-content/uploads/2026/01/hero.webp`), never as full URLs.
 *
 * That keeps the origin in one place. During the rebuild it points at the live
 * WordPress site so the replica looks right immediately; before launch it moves
 * to local files or Supabase Storage by changing this base — no content file
 * gets edited, and no `*.vercel.app` URL is ever written into shipped code.
 */
import manifest from '@/data/image-sizes.json';

const BASE = (process.env.NEXT_PUBLIC_IMAGE_BASE || '').replace(/\/+$/, '');

export function imageUrl(path) {
  if (!path) return null;
  if (/^https?:\/\//i.test(path)) return path; // already absolute
  const clean = path.startsWith('/') ? path : `/${path}`;
  return BASE ? `${BASE}${clean}` : clean;
}

/**
 * Standard `sizes` values, named after the layout that produces them.
 *
 * `sizes` describes the CSS box, so it belongs to the layout rather than to the
 * image — which is why these are named for where they are used. Getting one
 * wrong costs bandwidth or sharpness silently, so there are few of them and each
 * is written next to the grid it describes.
 */
export const SIZES = {
  /** 3-up product grid inside a max-w-5xl column. */
  productCard: '(min-width: 1024px) 320px, (min-width: 640px) 45vw, 92vw',
  /** The image column on a product page. */
  productHero: '(min-width: 640px) 20rem, 92vw',
  /** Body images in prose, which run the full measure. */
  prose: '(min-width: 1024px) 64rem, 92vw',
};

/**
 * Resolve a content image path to a full responsive candidate set.
 *
 * Returns `{ src, srcSet, width, height }`. `srcSet` is undefined when the
 * upload has no usable variants, so callers can spread the result onto an <img>
 * either way and simply get a plain single-source image.
 *
 * The candidates come from data/image-sizes.json, which scripts/mirror-image-
 * sizes.mjs generates from files that are actually on disk — so a width is
 * never advertised to the browser unless it can be served.
 */
/**
 * Paths the content references but that cannot be served — gone from the live
 * WordPress server and absent from the developer's originals. Rendering them
 * would put a broken-image icon on the page, so callers get `src: null` and skip
 * the image entirely. Regenerated by scripts/mirror-image-sizes.mjs, so a file
 * that later becomes available simply starts rendering.
 */
const MISSING = new Set(manifest.missing ?? []);

export function imageSource(path) {
  if (!path) return { src: null };

  const src = imageUrl(path);
  if (/^https?:\/\//i.test(path)) return { src };

  const clean = path.startsWith('/') ? path : `/${path}`;
  if (MISSING.has(clean)) return { src: null };
  const family = manifest.families[manifest.index[clean]];
  if (!family) return { src };

  // Only candidates that CROP THE SAME WAY as the referenced file.
  //
  // WordPress generates two kinds of size: hard crops to a fixed box
  // (`woocommerce_thumbnail` is 300x300 whatever the original) and proportional
  // scales (`large`, `full`). For a non-square upload those have different
  // aspect ratios, and a srcset containing both lets the browser swap a square
  // crop for a letterboxed scale purely on viewport width — the subject visibly
  // jumps. Matching the reference's ratio keeps every candidate interchangeable.
  const referenced = family.variants.find(([, , file]) => file === clean);
  const ratio = referenced?.[1] ? referenced[0] / referenced[1] : null;
  const sameCrop = ratio
    ? family.variants.filter(([w, h]) => h && Math.abs(w / h - ratio) / ratio < 0.02)
    : family.variants;

  if (sameCrop.length < 2) return { src };

  return {
    src,
    srcSet: sameCrop.map(([width, , file]) => `${imageUrl(file)} ${width}w`).join(', '),
    width: referenced?.[0] || family.width || undefined,
    height: referenced?.[1] || family.height || undefined,
  };
}
